declare(strict_types=1);

namespace Razy\Rzx\Compile;

use Closure;
use Razy\Rzx\CompileError;
use Razy\Rzx\ComponentMeta;
use Razy\Rzx\Expr\Call;
use Razy\Rzx\Expr\Expr;
use Razy\Rzx\Expr\Literal;
use Razy\Rzx\Expr\MapLiteral;
use Razy\Rzx\Node\AnchorNode;
use Razy\Rzx\Node\ComponentNode;
use Razy\Rzx\Node\DocumentNode;
use Razy\Rzx\Node\ElementNode;
use Razy\Rzx\Node\FillNode;
use Razy\Rzx\Node\ForNode;
use Razy\Rzx\Node\IfNode;
use Razy\Rzx\Node\Node;
use Razy\Rzx\Node\OutputNode;
use Razy\Rzx\Node\PushNode;
use Razy\Rzx\Node\SlotNode;
use Razy\Rzx\Node\TextNode;
use Razy\Rzx\Prop;
use Razy\Rzx\Runtime\Escape;
use Razy\Rzx\Source;

/**
 * Markup AST to the body of a PHP render closure.
 *
 * Static HTML is written at compile time; every `{…}` goes through a Runtime
 * escaping helper chosen by its position (text, attribute, URL attribute,
 * JSON script). Conditions become `if`, loops `foreach`, fills and push
 * bodies closures. Component uses are generated by ComponentCall.
 */
final class CodeGen
{
    /** Closure header shared by fills and push bodies. */
    public const CLOSURE = 'static function () use ($__s, $__rt, $__slots): void {';

    /** SVG elements that animate attributes of another element (names as the HTML parser lowercases them). */
    private const SVG_ANIMATION = ['animate', 'set', 'animatemotion', 'animatetransform', 'animatecolor', 'discard'];

    /** What an SVG animation may target: presentational attributes only. */
    private const ANIMATABLE = [
        'opacity', 'fill-opacity', 'stroke-opacity', 'transform', 'fill', 'stroke', 'color', 'visibility', 'display',
        'x', 'y', 'x1', 'y1', 'x2', 'y2', 'dx', 'dy', 'width', 'height', 'r', 'rx', 'ry', 'cx', 'cy',
        'd', 'points', 'offset', 'stop-color', 'stop-opacity', 'font-size', 'letter-spacing', 'rotate',
        'pathLength', 'startOffset', 'viewBox', 'stdDeviation',
    ];

    /** `<meta http-equiv>` values other than refresh that may appear. */
    private const PRAGMAS = ['content-type', 'content-language', 'default-style', 'x-ua-compatible'];

    public readonly Writer $out;

    public readonly ExprGen $expr;

    private int $counter = 0;

    private int $pushDepth = 0;

    private ComponentCall $components;

    /**
     * @param Closure(string, int): ComponentMeta $metaFor resolves a used component's contract
     */
    public function __construct(public readonly Source $source, Closure $metaFor)
    {
        $this->out = new Writer($source);
        $this->expr = new ExprGen($source);
        $this->components = new ComponentCall($this, $metaFor);
    }

    /**
     * Generate the statements that render $doc; the caller wraps them in the closure.
     */
    public function document(DocumentNode $doc, ComponentMeta $self): void
    {
        $this->expr->push($self->props);
        if ($doc->root instanceof ElementNode && $doc->root->tag === 'html') {
            $this->out->html('<!DOCTYPE html>');
        }
        $this->nodes([$doc->root, ...$doc->pushes]);
        $this->expr->pop();
    }

    /**
     * @param list<Node> $nodes
     */
    public function nodes(array $nodes): void
    {
        foreach ($nodes as $node) {
            $this->node($node);
        }
    }

    /** A fresh suffix for generated temporaries (`$__f3`). */
    public function id(): int
    {
        return ++$this->counter;
    }

    public function site(int $offset): string
    {
        [$line] = $this->source->position($offset);

        return \basename($this->source->file) . ':' . $line;
    }

    public function error(string $code, string $reason, int $offset): CompileError
    {
        return new CompileError($code, $reason, $this->source, $offset);
    }

    private function node(Node $node): void
    {
        match (true) {
            $node instanceof TextNode => $this->out->html($node->text),
            $node instanceof OutputNode => $this->output($node),
            $node instanceof ElementNode => $this->element($node),
            $node instanceof ComponentNode => $this->components->generate($node),
            $node instanceof IfNode => $this->ifNode($node),
            $node instanceof ForNode => $this->forNode($node),
            $node instanceof SlotNode => $this->slot($node),
            $node instanceof PushNode => $this->push($node),
            $node instanceof AnchorNode => $this->out->statement('echo $__rt->marker(' . \var_export($node->name, true) . ');', $node->offset),
            $node instanceof FillNode => throw $this->error('RZX124', '<Fill> must be a direct child of a component', $node->offset),
            default => throw $this->error('RZX100', 'Unsupported node', $node->offset),
        };
    }

    private function output(OutputNode $node): void
    {
        $expr = $node->expr;
        if ($expr instanceof Call && $expr->name === 'html') {
            if (\count($expr->arguments) !== 1) {
                throw $this->error('RZX103', 'html() takes one argument', $expr->offset);
            }
            $arg = $expr->arguments[0];
            $type = $this->expr->typeOf($arg);
            if ($arg instanceof Literal || ($type !== null && $type->type !== 'html' && $type->type !== 'any')) {
                throw $this->error('RZX137', 'html() needs a SafeHtml value (a Prop::html() prop); a string is always escaped', $arg->offset);
            }
            $this->out->statement('echo $__rt->safe(' . $this->expr->compile($arg) . ');', $node->offset);

            return;
        }
        $this->out->statement('echo $__rt->text(' . $this->expr->compile($expr) . ');', $node->offset);
    }

    private function element(ElementNode $node): void
    {
        $tag = $node->tag;
        if ($tag === 'style') {
            throw $this->error('RZX130', '<style> is not allowed; style comes from tokens and hooks={{…}}', $node->offset);
        }
        if ($tag === 'script') {
            $this->script($node);

            return;
        }
        $this->animation($node);
        $this->out->html('<' . $tag);
        $this->attributes($node);
        $this->out->html('>');
        if ($node->void) {
            return; // <br>, <br/>: no end tag
        }
        $this->nodes($node->children);
        $this->out->html('</' . $tag . '>');
    }

    /**
     * `<script src>` with no body, or a JSON / importmap script whose body is
     * one expression, JSON-encoded so `</script>` cannot close it. Inline JS
     * is a compile error.
     */
    private function script(ElementNode $node): void
    {
        $type = null;
        $src = false;
        foreach ($node->attributes as $attr) {
            $type = $attr->name === 'type' ? $attr->literal : $type;
            $src = $src || $attr->name === 'src';
        }
        $body = $node->children;
        $output = null;
        if ($src) {
            if ($body !== []) {
                throw $this->error('RZX133', '<script src> must be empty', $body[0]->offset);
            }
        } elseif (!\in_array($type, ['application/json', 'importmap'], true)) {
            throw $this->error('RZX133', 'Inline JavaScript is not allowed; use <script type="module" src={asset(…)} />', $node->offset);
        } elseif (\count($body) !== 1 || !$body[0] instanceof OutputNode) {
            throw $this->error('RZX133', 'A ' . $type . ' script holds exactly one expression, e.g. {data}', ($body[0] ?? $node)->offset);
        } else {
            $output = $body[0];
        }
        $this->out->html('<script');
        $this->attributes($node);
        $this->out->html('>');
        if ($output !== null) {
            $value = $output->expr;
            if ($value instanceof Call && $value->name === 'json' && \count($value->arguments) === 1) {
                $value = $value->arguments[0];
            }
            $this->out->statement('echo $__rt->jsonScript(' . $this->expr->compile($value) . ');', $output->offset);
        }
        $this->out->html('</script>');
    }

    /**
     * SVG animation elements can write any attribute of their target, links
     * included (`<set attributeName="href" to="javascript:…">`), which no
     * per-attribute escaping sees. So their target and values are literals,
     * and the target (entity-decoded) must be a presentational attribute on
     * an allowlist; anything else, `href`, `on*` or an odd spelling, is RZX138.
     */
    private function animation(ElementNode $node): void
    {
        $this->navigation($node);
        if (!\in_array($node->tag, self::SVG_ANIMATION, true)) {
            return;
        }
        foreach ($node->attributes as $attr) {
            $name = \strtolower($attr->name);
            if (\in_array($name, ['attributename', 'to', 'from', 'values', 'by', 'href', 'xlink:href'], true) && $attr->expr !== null) {
                throw $this->error('RZX138', '<' . $node->tag . '> ' . $attr->name . ' must be a literal; an animation can rewrite any attribute of its target', $attr->offset);
            }
            if ($name === 'attributename') {
                $target = \trim(Escape::decode((string) $attr->literal));
                if (!\in_array($target, self::ANIMATABLE, true) && !\preg_match('/^stroke-[a-z]+(?:-[a-z]+)?$/', $target)) {
                    throw $this->error('RZX138', '<' . $node->tag . '> cannot animate "' . $target . '"; only presentational attributes (opacity, transform, fill, stroke-*, x, y, …) can be animated', $attr->offset);
                }
            }
        }
    }

    /**
     * Elements whose value redirects the page or re-bases every relative URL
     * take literals only: `<base>` and a pragma `<meta http-equiv>`. A refresh
     * must be exactly `<seconds>[;|, [url=]<url>]` with a safe URL; other
     * pragmas come from an allowlist.
     */
    private function navigation(ElementNode $node): void
    {
        if ($node->tag !== 'base' && $node->tag !== 'meta') {
            return;
        }
        $pragma = null;
        $content = null;
        foreach ($node->attributes as $attr) {
            $name = \strtolower($attr->name);
            if ($name === 'http-equiv') {
                $pragma = $attr;
            } elseif ($name === 'content') {
                $content = $attr;
            }
        }
        foreach ($node->attributes as $attr) {
            $name = \strtolower($attr->name);
            // <meta name="csrf-token" content={token}> stays allowed: only a pragma's content can redirect.
            if ($attr->expr !== null && ($node->tag === 'base' || $name === 'http-equiv' || ($name === 'content' && $pragma !== null))) {
                throw $this->error('RZX139', '<' . $node->tag . '> ' . $attr->name . ' must be a literal (it can redirect the page or re-base its links)', $attr->offset);
            }
        }
        if ($pragma === null) {
            return;
        }
        $kind = \strtolower(\trim(Escape::decode((string) $pragma->literal)));
        if ($kind !== 'refresh') {
            if (!\in_array($kind, self::PRAGMAS, true)) {
                throw $this->error('RZX139', '<meta http-equiv="' . $kind . '"> is not allowed (allowed: refresh, ' . \implode(', ', self::PRAGMAS) . ')', $pragma->offset);
            }

            return;
        }
        $value = Escape::decode((string) $content?->literal);
        if (!\preg_match('/^\s*\d+(?:\.\d*)?\s*(?:[;,]\s*(?:url\s*=\s*)?(.*?))?\s*$/is', $value, $m)) {
            throw $this->error('RZX134', 'A meta refresh must be "<seconds>" or "<seconds>; url=<url>"', ($content ?? $pragma)->offset);
        }
        $url = \trim($m[1] ?? '');
        if (\strlen($url) >= 2 && ($url[0] === "'" || $url[0] === '"') && \str_ends_with($url, $url[0])) {
            $url = \substr($url, 1, -1);
        }
        if ($url !== '' && (\preg_match('/\s/', $url) || !Escape::isSafeUrl($url))) {
            throw $this->error('RZX134', 'Unsafe URL in a meta refresh', ($content ?? $pragma)->offset);
        }
    }

    private function attributes(ElementNode $node): void
    {
        foreach ($node->attributes as $attr) {
            $name = $attr->name;
            $lower = \strtolower($name);
            if ($lower === 'style') {
                throw $this->error('RZX131', 'style="" is not allowed; set public hooks with hooks={{ \'--name\': value }}', $attr->offset);
            }
            if (\preg_match('/^on[a-z]+$/', $lower)) {
                throw $this->error('RZX132', 'Inline event handlers (' . $name . ') are not allowed; behaviour belongs in a module script', $attr->offset);
            }
            if ($lower === 'srcdoc') {
                throw $this->error('RZX135', 'srcdoc is not allowed (it is raw HTML)', $attr->offset);
            }
            if ($name === 'hooks') {
                $this->hooks($attr->expr, $attr->offset);
                continue;
            }
            if ($attr->isBoolean()) {
                $this->out->html(' ' . $name);
            } elseif ($attr->literal !== null) {
                $decoded = Escape::decode($attr->literal);
                $unsafe = \in_array($lower, Escape::URL_ATTRIBUTES, true) ? !Escape::isSafeUrl($decoded)
                    : (\in_array($lower, Escape::SRCSET_ATTRIBUTES, true) && !Escape::isSafeSrcset($decoded));
                if ($unsafe) {
                    throw $this->error('RZX134', 'Unsafe URL in ' . $name . '; only http, https, mailto and relative URLs are allowed', $attr->offset);
                }
                $this->out->html(' ' . $name . '="' . \str_replace(['"', '<', '>'], ['&quot;', '&lt;', '&gt;'], $attr->literal) . '"');
            } elseif ($attr->expr !== null) {
                $this->out->statement('echo $__rt->attr(' . \var_export($name, true) . ', ' . $this->expr->compile($attr->expr) . ');', $attr->offset);
            }
        }
    }

    private function hooks(?Expr $map, int $offset): void
    {
        if (!$map instanceof MapLiteral) {
            throw $this->error('RZX136', 'hooks takes a map: hooks={{ \'--name\': value }}', $offset);
        }
        $items = [];
        foreach ($map->entries as [$key, $value]) {
            if (!$key instanceof Literal || !\is_string($key->value) || !\preg_match('/^--[a-z0-9]+(?:-[a-z0-9]+)*$/', $key->value)) {
                throw $this->error('RZX136', 'A hook name is a literal custom property, e.g. \'--card-gap\'', $key->offset);
            }
            $items[] = \var_export($key->value, true) . ' => ' . $this->expr->compile($value);
        }
        $this->out->statement('echo $__rt->hooks([' . \implode(', ', $items) . ']);', $offset);
    }

    private function ifNode(IfNode $node): void
    {
        foreach ($node->branches as $i => [$test, $children]) {
            $condition = '$__rt->truthy(' . $this->expr->compile($test) . ')';
            if ($i === 0) {
                $this->out->open('if (' . $condition . ') {', $node->offset);
            } else {
                $this->out->close('} elseif (' . $condition . ') {');
            }
            $this->nodes($children);
        }
        if ($node->else !== null) {
            $this->out->close('} else {');
            $this->nodes($node->else);
        }
        $this->out->close();
    }

    private function forNode(ForNode $node): void
    {
        foreach (\array_filter([$node->as, $node->index]) as $name) {
            if ($this->expr->declared($name)) {
                throw $this->error('RZX104', '<for> variable `' . $name . '` shadows a prop or an outer loop variable', $node->offset);
            }
        }
        $id = $this->id();
        $list = $this->expr->compile($node->each);
        $type = $this->expr->typeOf($node->each);
        $this->out->statement('$__c' . $id . ' = 0;', $node->offset);
        if ($node->key !== null) {
            $this->out->statement('$__k' . $id . ' = [];', $node->offset);
        }
        $this->out->open('foreach ($__rt->iter(' . $list . ') as $__v' . $id . ') {', $node->offset);
        $this->out->statement('$__s[' . \var_export($node->as, true) . '] = $__v' . $id . ';', $node->offset);
        if ($node->index !== null) {
            $this->out->statement('$__s[' . \var_export($node->index, true) . '] = $__c' . $id . ';', $node->offset);
        }
        if ($node->key !== null) {
            $this->out->statement('$__rt->loopKey($__k' . $id . ', $__v' . $id . ', ' . \var_export($node->key, true) . ', ' . \var_export($this->site($node->offset), true) . ');', $node->offset);
        }
        $names = [$node->as => $type?->type === 'list' ? $type->item : null];
        if ($node->index !== null) {
            $names[$node->index] = Prop::int();
        }
        $this->expr->push($names);
        $this->nodes($node->children);
        $this->expr->pop();
        $this->out->statement('++$__c' . $id . ';', $node->offset);
        $this->out->close();
        if ($node->empty !== null) {
            $this->out->open('if ($__c' . $id . ' === 0) {', $node->offset);
            $this->nodes($node->empty);
            $this->out->close();
        }
    }

    private function slot(SlotNode $node): void
    {
        $name = match (true) {
            $node->name === null => "''",
            \is_string($node->name) => \var_export($node->name, true),
            default => '$__rt->str(' . $this->expr->compile($node->name) . ')',
        };
        $id = $this->id();
        $this->out->statement('$__n' . $id . ' = ' . $name . ';', $node->offset);
        $this->out->open('if ($__slots->has($__n' . $id . ')) {', $node->offset);
        $this->out->statement('$__slots->render($__n' . $id . ');', $node->offset);
        if ($node->fallback !== []) {
            $this->out->close('} else {');
            $this->nodes($node->fallback);
        }
        $this->out->close();
    }

    private function push(PushNode $node): void
    {
        if ($this->pushDepth > 0) {
            throw $this->error('RZX140', '<push> cannot be nested inside another <push>', $node->offset);
        }
        $order = $node->order === null ? '0' : '(int) $__rt->num(' . $this->expr->compile($node->order) . ')';
        $this->out->open('$__rt->push(' . \var_export($node->to, true) . ', $__rt->capture(' . self::CLOSURE, $node->offset);
        ++$this->pushDepth;
        $this->nodes($node->children);
        --$this->pushDepth;
        $this->out->close('}), ' . \var_export($node->key, true) . ', ' . $order . ');');
    }
}
