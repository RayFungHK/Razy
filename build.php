<?php

/**
 * Razy Framework — PHAR Build Script
 *
 * Builds Razy.phar from the src/ directory and optionally copies it to
 * one or more target paths. The archive is reproducible: files are added in
 * sorted path order, every entry shares one timestamp, and the stub, alias,
 * gzip compression and SHA256 signature are fixed.
 *
 * Timestamp, in order: SOURCE_DATE_EPOCH (digits only), else the git commit
 * time of HEAD when this directory is a checkout, else 0.
 *
 * Usage:
 *   php build.php [path1] [path2] ...
 *
 * Examples:
 *   php build.php                                  # Build Razy.phar in project root
 *   php build.php /var/www/mysite                  # Build and copy to /var/www/mysite/Razy.phar
 *   php build.php ./site-a ./site-b ../staging     # Build and copy to multiple locations
 */

declare(strict_types=1);

/**
 * Digits in SOURCE_DATE_EPOCH, else HEAD's commit time, else 0.
 */
function razy_source_date(string $root): int
{
    $env = getenv('SOURCE_DATE_EPOCH');
    if (is_string($env) && preg_match('/^\d+$/', $env) === 1) {
        $epoch = (int) $env;
        if ($epoch > 0xffffffff) {
            throw new RuntimeException('SOURCE_DATE_EPOCH does not fit a phar timestamp');
        }

        return $epoch;
    }

    $git = $root . DIRECTORY_SEPARATOR . '.git';
    if (!is_file($git) && !is_dir($git)) {
        return 0;
    }

    return razy_git_commit_time($root);
}

/**
 * Committer time of HEAD. 0 when git cannot answer. Does not search parent directories.
 */
function razy_git_commit_time(string $root): int
{
    $proc = proc_open(
        ['git', '-C', $root, 'log', '-1', '--format=%ct'],
        [1 => ['pipe', 'w'], 2 => ['pipe', 'w']],
        $pipes
    );
    if (!is_resource($proc)) {
        return 0;
    }
    $out = stream_get_contents($pipes[1]);
    fclose($pipes[1]);
    fclose($pipes[2]);
    $code = proc_close($proc);
    $line = trim((string) $out);
    if ($code !== 0 || preg_match('/^\d+$/', $line) !== 1) {
        return 0;
    }
    $epoch = (int) $line;
    if ($epoch > 0xffffffff) {
        return 0;
    }

    return $epoch;
}

/**
 * Regular files under src/, the set Phar::buildFromDirectory would add.
 * Hidden files are included. Directories and symlinks are not. Paths use /.
 *
 * @return array<string, string> archive path => filesystem path
 */
function razy_collect_files(string $srcDir): array
{
    if (!is_dir($srcDir)) {
        throw new RuntimeException("source directory not found: $srcDir");
    }
    $files = [];
    $dir = new RecursiveIteratorIterator(
        new RecursiveDirectoryIterator($srcDir, FilesystemIterator::SKIP_DOTS)
    );
    foreach ($dir as $file) {
        if (!$file->isFile() || $file->isLink()) {
            continue;
        }
        $local = str_replace('\\', '/', $dir->getSubPathname());
        $files[$local] = $file->getPathname();
    }
    ksort($files, SORT_STRING);

    return $files;
}

/**
 * FQCN => path under library/. Library files are scanned in path order so the
 * first declaration of a duplicate FQCN does not depend on directory order.
 *
 * @return array<string, string>
 */
function razy_classmap(string $libraryDir): array
{
    $root = realpath($libraryDir);
    if ($root === false) {
        throw new RuntimeException("library directory not found: $libraryDir");
    }
    $libRoot = rtrim(str_replace('\\', '/', $root), '/') . '/';
    $paths = [];
    $dir = new RecursiveIteratorIterator(
        new RecursiveDirectoryIterator($libraryDir, FilesystemIterator::SKIP_DOTS)
    );
    foreach ($dir as $file) {
        if (!$file->isFile() || $file->isLink() || 'php' !== $file->getExtension()) {
            continue;
        }
        $real = realpath($file->getPathname());
        if ($real === false) {
            continue;
        }
        $relative = substr(str_replace('\\', '/', $real), strlen($libRoot));
        $paths[$relative] = $file->getPathname();
    }
    ksort($paths, SORT_STRING);

    $classmap = [];
    foreach ($paths as $relative => $full) {
        $src = file_get_contents($full);
        if ($src === false || !preg_match('/^\s*namespace\s+([^\s;]+)/m', $src, $ns)) {
            continue;
        }
        $namespace = trim($ns[1]);
        if (!preg_match_all('/^\s*(?:(?:final|abstract|readonly)\s+)*(?:class|interface|trait|enum)\s+([A-Za-z_]\w*)/m', $src, $types)) {
            continue;
        }
        foreach ($types[1] as $type) {
            $classmap[$namespace . '\\' . $type] ??= $relative;
        }
    }
    ksort($classmap);

    return $classmap;
}

/**
 * @param array<string, string> $classmap
 */
function razy_classmap_php(array $classmap): string
{
    return "<?php\n\n/**\n * Baked classmap — generated by build.php at phar build time. Never edit.\n * Count: " . count($classmap) . " classes.\n */\n\nreturn " . var_export($classmap, true) . ";\n";
}

/**
 * Add every entry from a temp file touched to $epoch, in key order.
 * $files values are filesystem paths, or ['bytes' => string] for generated files.
 * Entry mode is 0644 so the archive does not depend on the source mode or umask.
 *
 * @param array<string, string|array{bytes: string}> $files
 */
function razy_add_entries(Phar $phar, array $files, int $epoch): void
{
    $tmp = tempnam(sys_get_temp_dir(), 'rzy');
    if ($tmp === false) {
        throw new RuntimeException('could not create a temp file');
    }
    try {
        foreach ($files as $local => $source) {
            $bytes = is_array($source) ? $source['bytes'] : file_get_contents($source);
            if (!is_string($bytes)) {
                throw new RuntimeException('could not read ' . $local);
            }
            if (file_put_contents($tmp, $bytes) === false || !chmod($tmp, 0644) || !touch($tmp, $epoch)) {
                throw new RuntimeException('could not stage ' . $local);
            }
            $name = (string) $local;
            $phar->addFile($tmp, $name);
            $phar[$name]->chmod(0644);
        }
    } finally {
        if (is_file($tmp)) {
            unlink($tmp);
        }
    }
}

/**
 * Little-endian uint32 at $pos.
 */
function razy_u32(string $data, int $pos): int
{
    if ($pos < 0 || $pos + 4 > strlen($data)) {
        throw new RuntimeException('phar truncated at offset ' . $pos);
    }
    $unpacked = unpack('V', substr($data, $pos, 4));

    return (int) $unpacked[1];
}

/**
 * @return array{0: string, 1: int} hash name and signature length
 */
function razy_signature_spec(int $flags): array
{
    $algo = $flags & 0xff;
    if ($flags !== $algo) {
        throw new RuntimeException('unsupported phar signature flags ' . $flags);
    }
    $spec = [
        1 => ['md5', 16],
        2 => ['sha1', 20],
        3 => ['sha256', 32],
        4 => ['sha512', 64],
    ];
    if (!isset($spec[$algo])) {
        throw new RuntimeException('unsupported phar signature algorithm ' . $algo);
    }

    return $spec[$algo];
}

/**
 * Debian's php-phar writes every entry timestamp as 0 and ignores both the
 * file mtime and SOURCE_DATE_EPOCH. Rewrite the manifest timestamps and
 * resign so the stamp is $epoch on every PHP build. Call this last: a later
 * Phar write puts the zeros back.
 */
function razy_fix_timestamps(string $pharPath, int $epoch): void
{
    $data = file_get_contents($pharPath);
    if ($data === false) {
        throw new RuntimeException("could not read $pharPath");
    }
    if (substr($data, -4) !== 'GBMB') {
        throw new RuntimeException('phar is missing its signature magic');
    }
    $flagWord = razy_u32($data, strlen($data) - 8);
    [$hashName, $sigLen] = razy_signature_spec($flagWord);
    $bodyLen = strlen($data) - $sigLen - 8;
    $halt = strpos($data, '__HALT_COMPILER();');
    if ($halt === false) {
        throw new RuntimeException('phar stub has no __HALT_COMPILER()');
    }
    $close = strpos($data, '?>', $halt);
    if ($close === false) {
        throw new RuntimeException('phar stub has no closing tag');
    }
    $off = $close + 2;
    if (substr($data, $off, 2) === "\r\n") {
        $off += 2;
    } elseif (isset($data[$off]) && ($data[$off] === "\n" || $data[$off] === "\r")) {
        $off += 1;
    }
    $manifestLen = razy_u32($data, $off);
    $start = $off + 4;
    $end = $start + $manifestLen;
    if ($end > $bodyLen) {
        throw new RuntimeException('phar manifest overruns the archive');
    }

    $cursor = $start;
    $count = razy_u32($data, $cursor);
    $cursor += 4;
    $cursor += 2;
    $cursor += 4;
    $aliasLen = razy_u32($data, $cursor);
    $cursor += 4 + $aliasLen;
    $metaLen = razy_u32($data, $cursor);
    $cursor += 4 + $metaLen;

    $stampAt = [];
    for ($i = 0; $i < $count; $i++) {
        $nameLen = razy_u32($data, $cursor);
        $cursor += 4 + $nameLen;
        $cursor += 4;
        $stampAt[] = $cursor;
        $cursor += 4;
        $cursor += 4;
        $cursor += 4;
        $cursor += 4;
        $fileMeta = razy_u32($data, $cursor);
        $cursor += 4 + $fileMeta;
    }
    if ($cursor !== $end) {
        throw new RuntimeException(
            'phar manifest walk ended at ' . $cursor . ', expected ' . $end
            . ', head ' . bin2hex(substr($data, $start, 24))
        );
    }

    $chunks = [];
    $pos = 0;
    $packed = pack('V', $epoch);
    foreach ($stampAt as $at) {
        $chunks[] = substr($data, $pos, $at - $pos);
        $chunks[] = $packed;
        $pos = $at + 4;
    }
    $chunks[] = substr($data, $pos, $bodyLen - $pos);
    $body = implode('', $chunks);
    $signed = $body . hash($hashName, $body, true) . pack('V', $flagWord) . 'GBMB';
    if (file_put_contents($pharPath, $signed) === false) {
        throw new RuntimeException("could not write $pharPath");
    }
}

try {
    $pharFile = 'Razy.phar';
    // One absolute path for build, chmod and copy. A bare 'Razy.phar' resolves
    // against the CWD while the chmod/copy below used __DIR__, so running the
    // script from another directory built one file and chmod'ed another.
    $pharPath = __DIR__ . DIRECTORY_SEPARATOR . $pharFile;
    $epoch = razy_source_date(__DIR__);

    if (file_exists($pharPath)) {
        unlink($pharPath);
    }
    if (file_exists($pharPath . '.gz')) {
        unlink($pharPath . '.gz');
    }

    $srcDir = __DIR__ . DIRECTORY_SEPARATOR . 'src';
    $files = razy_collect_files($srcDir);
    $classmap = razy_classmap($srcDir . DIRECTORY_SEPARATOR . 'library');
    $files['system/classmap.php'] = ['bytes' => razy_classmap_php($classmap)];
    ksort($files, SORT_STRING);

    $phar = new Phar($pharPath);
    $phar->startBuffering();
    $phar->setAlias($pharFile);
    $stub = "#!/usr/bin/env php \n" . $phar->createDefaultStub('main.php');
    razy_add_entries($phar, $files, $epoch);
    $phar->setStub($stub);
    $phar->stopBuffering();
    $phar->compressFiles(Phar::GZ);
    $phar->setSignatureAlgorithm(Phar::SHA256);
    // After this, do not call Phar write methods: they store timestamp 0 again.
    razy_fix_timestamps($pharPath, $epoch);

    echo 'classmap: ' . count($classmap) . ' classes baked' . PHP_EOL;

    if (PHP_OS_FAMILY !== 'Windows' && !chmod($pharPath, 0770)) {
        throw new RuntimeException("Could not chmod $pharPath");
    }

    echo "$pharPath successfully created" . PHP_EOL;

    $targets = array_slice($argv, 1);
    foreach ($targets as $target) {
        $target = rtrim($target, '/\\');
        if (!is_dir($target)) {
            echo "  [SKIP] Directory does not exist: $target" . PHP_EOL;
            continue;
        }
        $dest = $target . DIRECTORY_SEPARATOR . $pharFile;
        if (copy($pharPath, $dest)) {
            echo "  [OK]   Copied to $dest" . PHP_EOL;
        } else {
            echo "  [FAIL] Could not copy to $dest" . PHP_EOL;
        }
    }
} catch (Exception $e) {
    fwrite(STDERR, $e->getMessage() . PHP_EOL);
    exit(1);
}
