declare(strict_types=1);

namespace Razy\Tests;

use PHPUnit\Framework\Attributes\CoversClass;
use PHPUnit\Framework\TestCase;
use Razy\Database\Schema\PostgresGrammar;
use Razy\Database\Table;
use Razy\Exception\DatabaseException;

#[CoversClass(PostgresGrammar::class)]
class PostgresGrammarTest extends TestCase
{
    public function testCreateTableMapsTypesKeysAndDefaults(): void
    {
        $table = new Table('app_users');
        $table->addColumn('user_id=type(auto)');
        $table->addColumn('login=type(text),length(64),key(unique)');
        $table->addColumn('email=type(text),nullable');
        $table->addColumn('bio=type(full_text)');
        $table->addColumn('is_admin=type(bool)');
        $table->addColumn('credits=type(int),default(5)');
        $table->addColumn('balance=type(decimal),length(10,2)');
        $table->addColumn('ratio=type(double)');
        $table->addColumn('settings=type(json)');
        $table->addColumn('created_at=type(datetime),oncreate');
        $table->addColumn('avatar=type(blob),nullable');
        $table->addColumn('team_id=type(int),key(index)');

        $this->assertSame([
            'CREATE TABLE IF NOT EXISTS "app_users" ('
            . '"user_id" INTEGER GENERATED BY DEFAULT AS IDENTITY, '
            . '"login" VARCHAR(64) NOT NULL DEFAULT \'\', '
            . '"email" VARCHAR(255) NULL DEFAULT NULL, '
            . '"bio" TEXT NULL DEFAULT NULL, '
            . '"is_admin" BOOLEAN NOT NULL DEFAULT \'0\', '
            . '"credits" INTEGER NOT NULL DEFAULT \'5\', '
            . '"balance" NUMERIC(10,2) NOT NULL DEFAULT \'0\', '
            . '"ratio" DOUBLE PRECISION NOT NULL DEFAULT \'0\', '
            . '"settings" JSONB NULL DEFAULT NULL, '
            . '"created_at" TIMESTAMP(0) NULL DEFAULT CURRENT_TIMESTAMP, '
            . '"avatar" BYTEA NULL DEFAULT NULL, '
            . '"team_id" INTEGER NOT NULL DEFAULT \'0\', '
            . 'PRIMARY KEY ("user_id"), '
            . 'UNIQUE ("login"))',
            'CREATE INDEX IF NOT EXISTS "app_users_team_id_idx" ON "app_users" ("team_id")',
        ], PostgresGrammar::createTable($table));
    }

    public function testDefaultsAndCommentsAreEscapedForPostgres(): void
    {
        $table = new Table('notes');
        $col = $table->addColumn('title=type(text)');
        $col->setDefault("O'Brien \\ back");
        $col->setComment("owner's title");

        $sql = PostgresGrammar::createTable($table);
        $this->assertStringContainsString("DEFAULT 'O''Brien \\ back'", $sql[0], 'a backslash is literal in standard Postgres strings; quotes double');
        $this->assertContains("COMMENT ON COLUMN \"notes\".\"title\" IS 'owner''s title'", $sql);
    }

    public function testForeignKeyFulltextAndGroupIndex(): void
    {
        $table = new Table('posts');
        $table->addColumn('post_id=type(auto)');
        $table->addColumn('author_id=type(int),reference(users,user_id)');
        $table->addColumn('body=type(full_text),key(fulltext)');
        $table->addColumn('slug=type(text)');
        $table->groupIndexing(['author_id', 'slug'], 'by_author_slug');

        $sql = PostgresGrammar::createTable($table);
        $this->assertStringContainsString('FOREIGN KEY ("author_id") REFERENCES "users" ("user_id")', $sql[0]);
        $this->assertContains('CREATE INDEX IF NOT EXISTS "posts_body_ftx" ON "posts" USING GIN (to_tsvector(\'simple\', coalesce("body", \'\')))', $sql);
        $this->assertContains('CREATE INDEX IF NOT EXISTS "posts_by_author_slug" ON "posts" ("author_id", "slug")', $sql);
    }

    public function testIdentifiersAreQuotedSafely(): void
    {
        $this->assertSame('"we""ird"', PostgresGrammar::quote('we"ird'));
    }

    public function testLongIndexNamesFitPostgresLimit(): void
    {
        $table = new Table(\str_repeat('t', 50));
        $table->addColumn(\str_repeat('c', 40) . '=type(int),key(index)');
        $sql = PostgresGrammar::createTable($table);
        \preg_match('/INDEX IF NOT EXISTS "([^"]+)"/', $sql[1], $m);
        $this->assertLessThanOrEqual(63, \strlen($m[1]));
    }

    public function testMysqlOnlyFeaturesAreRefusedNotGuessed(): void
    {
        foreach ([
            static fn (Table $t) => $t->addColumn('updated=type(timestamp),onupdate'),
            static fn (Table $t) => $t->addColumn('shape=type(geometry),key(spatial)'),
            static fn (Table $t) => $t->addColumn('mood=type(enum)'),
        ] as $i => $define) {
            $table = new Table('t' . $i);
            $define($table);
            try {
                PostgresGrammar::createTable($table);
                $this->fail("case {$i} rendered");
            } catch (DatabaseException) {
                $this->addToAssertionCount(1);
            }
        }
    }

    public function testAlterTable(): void
    {
        $table = new Table('app_users');
        $helper = $table->createHelper();
        $helper->dropForeignKey('fk_old');
        $helper->dropIndex('idx_old');
        $helper->dropColumn('legacy');
        $helper->addColumn('nickname=type(text),length(32),nullable', 'AFTER login');
        $helper->modifyColumn('credits', 'credits=type(bigint),default(10)');
        $helper->renameColumn('mail', 'email');
        $helper->addUniqueIndex('nickname', 'app_users_nickname_key');
        $helper->addForeignKey('team_id', 'teams', 'team_id', 'CASCADE');
        $helper->comment('people');
        $helper->rename('members');

        $this->assertSame([
            'ALTER TABLE "app_users" DROP CONSTRAINT IF EXISTS "fk_old"',
            'DROP INDEX IF EXISTS "idx_old"',
            'ALTER TABLE "app_users" DROP COLUMN "legacy"',
            'ALTER TABLE "app_users" RENAME COLUMN "mail" TO "email"',
            'ALTER TABLE "app_users" ADD COLUMN "nickname" VARCHAR(32) NULL DEFAULT NULL',
            'ALTER TABLE "app_users" ALTER COLUMN "credits" DROP DEFAULT',
            'ALTER TABLE "app_users" ALTER COLUMN "credits" TYPE BIGINT USING CAST("credits" AS BIGINT)',
            'ALTER TABLE "app_users" ALTER COLUMN "credits" SET NOT NULL',
            'ALTER TABLE "app_users" ALTER COLUMN "credits" SET DEFAULT \'10\'',
            'ALTER TABLE "app_users" ALTER COLUMN "email" DROP DEFAULT',
            'ALTER TABLE "app_users" ALTER COLUMN "email" TYPE VARCHAR(255) USING CAST("email" AS VARCHAR(255))',
            'ALTER TABLE "app_users" ALTER COLUMN "email" SET NOT NULL',
            'ALTER TABLE "app_users" ALTER COLUMN "email" SET DEFAULT \'\'',
            'CREATE UNIQUE INDEX IF NOT EXISTS "app_users_nickname_key" ON "app_users" ("nickname")',
            'ALTER TABLE "app_users" ADD CONSTRAINT "fk_app_users_team_id" FOREIGN KEY ("team_id") REFERENCES "teams" ("team_id") ON DELETE CASCADE',
            'COMMENT ON TABLE "app_users" IS \'people\'',
            'ALTER TABLE "app_users" RENAME TO "members"',
        ], PostgresGrammar::alterTable($helper));
    }

    public function testDroppingThePrimaryKeyUsesPostgresConstraintName(): void
    {
        $helper = (new Table('orders'))->createHelper();
        $helper->dropPrimaryKey();
        $this->assertSame(['ALTER TABLE "orders" DROP CONSTRAINT IF EXISTS "orders_pkey"'], PostgresGrammar::alterTable($helper));
    }

    public function testTableAndHelperPickTheGrammarByDriver(): void
    {
        $table = new Table('x');
        $table->addColumn('id=type(auto)');
        $this->assertSame(PostgresGrammar::createTable($table), $table->getStatements('pgsql'));
        $this->assertSame([$table->getSyntax()], $table->getStatements('mysql'), 'MySQL output is unchanged');

        $helper = $table->createHelper();
        $helper->dropColumn('y');
        $this->assertSame(PostgresGrammar::alterTable($helper), $helper->getStatements('pgsql'));
        $this->assertSame([$helper->getSyntax()], $helper->getStatements('mysql'));
        $this->assertSame([], (new Table('z'))->createHelper()->getStatements('pgsql'));
    }
}
